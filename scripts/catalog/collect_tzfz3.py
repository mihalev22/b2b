def fetch(session, query):
    for attempt in range(3):
        try:
            r = session.get(f"{BASE}?q={query}", timeout=20)
            if r.status_code == 200:
                time.sleep(DELAY)
                return r.json().get("items", [])
            time.sleep(3)
        except requests.RequestException:
            time.sleep(3)
    return []


