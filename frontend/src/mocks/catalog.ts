export const catalog: KtruPosition[] = raw.map(([ktru_code, ktru_name, chars]) => ({
  ktru_code,
  ktru_name,
  okpd2_code: ktru_code.split('-')[0],
  characteristics: chars.map(([name, value, unit]) => ({ name, value, unit })),
}));

export function findPosition(code: string): KtruPosition | undefined {
  return catalog.find((p) => p.ktru_code === code);
}

export function searchCatalog(q: string, limit: number): KtruPosition[] {
  const needle = q.trim().toLowerCase();
  return catalog
    .filter((p) => p.ktru_name.toLowerCase().includes(needle) || p.ktru_code.includes(needle))
    .slice(0, limit);
}
